"""oway index: rebuild every INDEX.md under _oway/ from the file headers."""
from __future__ import annotations

from pathlib import Path

from . import headers

GENERATED = "<!-- Generated by `oway index`. Do not edit: run it again. -->"
# Folders with their own writer: the keeper keeps its own INDEX.md, evidence and
# state are machine files. They are linked from the parent index, never rebuilt.
OWN_WRITER = ("keeper", "evidence", "state")


def _cell(value: str) -> str:
    return (value or "").replace("|", "\\|").replace("\n", " ")


def render(folder: Path, base: Path) -> str | None:
    """The INDEX.md text for one folder, or None when the folder has nothing to list."""
    rows: list[str] = []
    for sub in sorted(p for p in folder.iterdir() if p.is_dir() and not p.name.startswith(".")):
        if not _has_files(sub):
            continue
        own = folder == base and sub.name in OWN_WRITER
        if own and not (sub / "INDEX.md").exists():
            rows.append(f"| {sub.name}/ | folder | | | written by its own tool |")
        else:
            rows.append(f"| [{sub.name}/]({sub.name}/INDEX.md) | folder | | | |")
    for f in sorted(folder.iterdir()):
        if not f.is_file() or f.name.startswith(".") or f.name == "INDEX.md":
            continue
        if f.suffix == ".md" and f.name not in headers.NO_HEADER:
            h = headers.read(f) or {}
            rows.append(f"| [{f.name}]({f.name}) | {_cell(h.get('type', 'no header'))} | "
                        f"{_cell(h.get('state', ''))} | {_cell(h.get('approved', ''))} | "
                        f"{_cell(h.get('description', ''))} |")
        else:
            rows.append(f"| [{f.name}]({f.name}) | {'log' if f.name in headers.NO_HEADER else f.suffix.lstrip('.') or 'file'} | | | |")
    if not rows:
        return None
    title = folder.relative_to(base.parent).as_posix()
    return "\n".join([
        f"# Index of {title}", GENERATED, "",
        "| File | Type | State | Approved | Description |",
        "| --- | --- | --- | --- | --- |", *rows, "",
    ])


def _has_files(folder: Path) -> bool:
    return any(p.is_file() and p.name != "INDEX.md" and not p.name.startswith(".")
               for p in folder.rglob("*"))


def folders(oway: Path) -> list[Path]:
    out = [oway]
    for p in sorted(oway.rglob("*")):
        parts = p.relative_to(oway).parts
        if p.is_dir() and parts[0] not in OWN_WRITER and not any(x.startswith(".") for x in parts):
            out.append(p)
    return out


def build(oway: Path, check: bool = False) -> list[Path]:
    """Write (or with check=True, only compare) every INDEX.md. Returns the stale ones."""
    stale: list[Path] = []
    for folder in folders(oway):
        text = render(folder, oway)
        target = folder / "INDEX.md"
        if text is None:
            if target.exists():
                stale.append(target)
                if not check:
                    target.unlink()
            continue
        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current != text:
            stale.append(target)
            if not check:
                target.write_text(text, encoding="utf-8")
    return stale
